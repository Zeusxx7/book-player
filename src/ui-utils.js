export function escapeHtml(str) {
  return String(str ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function bookInitials(title = '') {
  const words = String(title).trim().split(/\s+/).filter(Boolean);
  if (words.length === 0) return 'L';
  if (words.length === 1) return words[0].slice(0, 2).toUpperCase();
  return (words[0][0] + words[1][0]).toUpperCase();
}

export function bookCoverGradient(title = '') {
  let hash = 0;
  const s = String(title || 'Lectio');
  for (let i = 0; i < s.length; i++) {
    hash = ((hash << 5) - hash + s.charCodeAt(i)) | 0;
  }
  const [top, bottom] = COVER_PALETTES[Math.abs(hash) % COVER_PALETTES.length];
  return `linear-gradient(155deg, ${top}, ${bottom})`;
}

export function bookCoverMarkup(book) {
  if (book?.coverDataUrl) {
    return `<img src="${escapeHtml(book.coverDataUrl)}" alt="" loading="lazy" />`;
  }
  const bg = bookCoverGradient(book?.title);
  return `<div class="cover-monogram" style="background: ${bg}"><span class="cover-spine" aria-hidden="true"></span><span class="cover-letters">${escapeHtml(bookInitials(book?.title))}</span></div>`;
}

export function showToast(container, message, options = {}) {
  const { actionLabel = '', onAction = null, duration = 4200, isError = false } = options;
  const toast = document.createElement('div');
  toast.className = isError ? 'toast toast-error' : 'toast';

  const textSpan = document.createElement('span');
  textSpan.textContent = message;
  toast.appendChild(textSpan);

  if (actionLabel && typeof onAction === 'function') {
    const actions = document.createElement('div');
    actions.className = 'toast-actions';
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = 'btn btn-accent btn-xs';
    btn.textContent = actionLabel;
    btn.addEventListener('click', () => {
      onAction();
      toast.remove();
    });
    actions.appendChild(btn);
    toast.appendChild(actions);
  }

  container.appendChild(toast);
  setTimeout(() => {
    toast.remove();
  }, duration);
}

export function downloadTextFile(filename, content, mimeType) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
